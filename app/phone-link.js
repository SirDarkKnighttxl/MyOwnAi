  async function plConnect() {
    if (plSocket) return
    let key = ''
    try { key = (await ipcRenderer.invoke('get-license'))?.key || '' } catch(e) {}
    if (!key) { plSetState('license'); plNextTry = Date.now() + 10 * 60 * 1000; return }
    if (plSocket || !plWanted()) return

    // A pairing code copied from another drive (or made before this drive had its own key)
    // must never be used: phones would reach the wrong computer. Make a fresh one for this drive.
    if (config.phonePairFor !== key) plNewSecret(key, 'pairing code was not made for this drive')

    plSetState('connecting')
    const sock = new WebSocket(PL_RELAY_URL)
    plSocket = sock

    sock.onopen = () => {
      sock.send(JSON.stringify({ type: 'hello', role: 'desktop', pairSecret: plSecret(), licenseKey: key }))
    }
    sock.onmessage = (ev) => {
      let m
      try { m = JSON.parse(ev.data) } catch(e) { return }
      plHandle(m)
    }
    sock.onerror = () => {}
    sock.onclose = (ev) => {
      if (plSocket === sock) plSocket = null
      if (ev.code === 4003) {
        plLog('WARN', 'Relay refused license')
        plSetState('license')
        plNextTry = Date.now() + 10 * 60 * 1000
        return
      }
      if (ev.code === 4006) {
        plLog('WARN', 'Relay says this pairing code was shared with another drive')
        plNewSecret(key, 'old code was shared with another drive')
        plSetState('repair')
        plNextTry = Date.now() + 3000
        return
      }
      if (ev.code === 4004) plLog('WARN', 'Another TANNIS took over this pairing')
      if (plWanted()) {
        plSetState(navigator.onLine ? 'connecting' : 'offline')
        plNextTry = Date.now() + plBackoff
        plBackoff = Math.min(plBackoff * 2, 60000)
      } else {
        plSetState('off')
      }
    }
  }

