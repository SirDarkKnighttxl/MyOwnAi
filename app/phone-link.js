  // Run a desktop action with pop-up boxes redirected to the phone,
  // so nothing can freeze TANNIS waiting for a click on the computer.
  async function plWithDialogs(confirmed, fn) {
    const orig = { confirm: window.confirm, alert: window.alert, prompt: window.prompt }
    const notes = []
    window.confirm = () => !!confirmed
    window.alert   = (msg) => { notes.push(plClean(msg, 400)) }
    window.prompt  = () => null
    try { await fn() }
    finally {
      setTimeout(() => { window.confirm = orig.confirm; window.alert = orig.alert; window.prompt = orig.prompt }, 1500)
    }
    return notes.join(' ')
  }

  async function plSettingsRequest(m) {
    if (pureLocalMode) {
      plSend({ type: 'settings', reqId: m.reqId, items: [], note: 'TANNIS is in Pure Local mode.', pureLocal: true })
      return
    }
    const overlay = document.getElementById('settings-overlay')
    try {
      if (m.type === 'settings-open') {
        const wasOpen = overlay && overlay.classList.contains('visible')
        await plWithDialogs(false, () => openSettings())
        if (!wasOpen && overlay) overlay.classList.remove('visible')   // don't pop Settings open on the computer screen
        await plSleep(400)   // some lists (like system voices) fill in a moment later
        plSendSettings(m.reqId)
        return
      }
      if (m.type === 'settings-get') { plSendSettings(m.reqId); return }

      if (m.type === 'settings-click') {
        const el = plFindRef(m.ref)
        if (!el) { plSendSettings(m.reqId, 'That setting changed. Try again.'); return }
        if (el.id === 'pure-local-toggle') return
        const note = await plWithDialogs(!!m.confirmed, () => el.click())
        await plSleep(250)
        plSendSettings(m.reqId, note)
        return
      }

      if (m.type === 'settings-set') {
        const el = plFindRef(m.ref)
        if (!el) { plSendSettings(m.reqId, 'That setting changed. Try again.'); return }
        const note = await plWithDialogs(false, () => {
          if (el.type === 'checkbox') el.checked = !!m.value
          else el.value = String(m.value == null ? '' : m.value).slice(0, 5000)
          el.dispatchEvent(new Event('input',  { bubbles: true }))
          el.dispatchEvent(new Event('change', { bubbles: true }))
        })
        await plSleep(150)
        plSendSettings(m.reqId, note)
        return
      }

      if (m.type === 'settings-save') {
        const wasOpen = overlay && overlay.classList.contains('visible')
        const note = await plWithDialogs(false, () => saveSettings())
        if (wasOpen && overlay) overlay.classList.remove('visible')
        plLog('INFO', 'Settings saved from phone')
        plSend({ type: 'settings-saved', reqId: m.reqId, note: note || null })
        plSend(plInfo())
        return
      }
    } catch(e) {
      plLog('ERROR', 'Phone settings action failed: ' + e.message)
      plSend({ type: 'settings', reqId: m.reqId, items: plScrapeSettings(), note: 'That did not work on your computer: ' + e.message, pureLocal: !!pureLocalMode })
    }
  }

  async function plRunQueue() {
    if (plWorking) return
    plWorking = true
    try {
      while (plQueue.length) {
        const m = plQueue.shift()
        try { await plDoSend(m) }
        catch(e) {
          plLog('ERROR', 'Phone message failed: ' + e.message)
          plSend({ type: 'fail', reqId: m.reqId, error: 'Something went wrong on your computer: ' + e.message })
        }
      }
    } finally {
      plWorking = false
    }
  }

  async function plDoSend(m) {
    const text = String(m.text || '').trim().slice(0, 8000)
    if (!text) return

    if (!plAppReady()) {
      plSend({ type: 'fail', reqId: m.reqId, error: 'TANNIS is still on the start screen. Pick a mode on your computer first.' })
      return
    }

    // Wait if the computer is already answering something
    if (generateAbortController) {
      plSend({ type: 'status', reqId: m.reqId, status: 'waiting' })
      while (generateAbortController) await plSleep(400)
    }

    // Switch to the chat the phone is in, or start a new one
    if (m.newChat) {
      startNewChat()
    } else if (m.chatId && m.chatId !== currentSessionId) {
      if ((sessions || []).some(s => s.id === m.chatId)) {
        loadSession(m.chatId)
      } else {
        plSend({ type: 'fail', reqId: m.reqId, error: 'That chat is not open on your computer (it may be inside a project).' })
        return
      }
    }
    if (!currentSessionId) startNewSession()

    plSend({ type: 'status', reqId: m.reqId, status: 'thinking', chatId: currentSessionId })

    const aiTA      = document.getElementById('ai-input-textarea')
    const draft     = inputEl.value
    const draftAI   = aiTA ? aiTA.value : ''
    const voiceWas  = voiceEnabled
    const before    = conversationHistory.length

    // Don't read phone replies out loud on the computer unless the user wants that
    if (!config.phoneSpeakOnComputer) voiceEnabled = false

    inputEl.value = text
    if (aiTA) aiTA.value = text
    try {
      await sendMessage()
    } finally {
      voiceEnabled = voiceWas
      if (!inputEl.value && draft) inputEl.value = draft
      if (aiTA && !aiTA.value && draftAI) aiTA.value = draftAI
    }

    let reply = null
    for (let i = conversationHistory.length - 1; i >= before; i--) {
      const h = conversationHistory[i]
      if (h && h.role === 'assistant') { reply = h.content; break }
    }
    if (reply != null && typeof reply !== 'string') reply = JSON.stringify(reply)

    const s = getCurrentSession()
    if (reply == null) {
      plSend({ type: 'fail', reqId: m.reqId, chatId: currentSessionId, error: 'TANNIS could not answer that. Check your computer for details.' })
    } else {
      plSend({ type: 'reply', reqId: m.reqId, chatId: currentSessionId, title: s ? s.title : 'Conversation', text: reply })
    }
  }

